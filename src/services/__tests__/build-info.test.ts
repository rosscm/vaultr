import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { readBuildInfo } from '../build-info.js';

describe('build identification', () => {
  it('reads revision metadata generated by the build path', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vaultr-build-info-'));
    const filePath = path.join(dir, 'build-info.json');
    fs.writeFileSync(filePath, JSON.stringify({ revision: 'abc123', builtAt: '2026-10-20T18:00:00.000Z' }));
    expect(readBuildInfo(filePath)).toEqual({ revision: 'abc123', builtAt: '2026-10-20T18:00:00.000Z' });
  });
});
